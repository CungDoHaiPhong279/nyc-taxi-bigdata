-- Analytical data mart schema version 2 (Gold/Silver STEP 5 source contracts).
-- CREATE IF NOT EXISTS never migrates a legacy table. Refuse the STEP 1 skeleton
-- explicitly; use the guarded, opt-in migrations/recreate_empty_analytics.sql only when
-- the existing analytics tables are empty.
DO $$
BEGIN
    IF to_regclass('analytics.dim_weather') IS NOT NULL
       AND NOT EXISTS (
           SELECT 1 FROM information_schema.columns
           WHERE table_schema = 'analytics' AND table_name = 'dim_weather'
             AND column_name = 'weather_timestamp_utc'
       ) THEN
        RAISE EXCEPTION 'Legacy analytics.dim_weather exists; use explicit guarded recreate after checking data';
    END IF;

    IF to_regclass('analytics.fact_trip') IS NOT NULL
       AND NOT EXISTS (
           SELECT 1 FROM information_schema.columns
           WHERE table_schema = 'analytics' AND table_name = 'fact_trip'
             AND column_name = 'source_year'
       ) THEN
        RAISE EXCEPTION 'Legacy analytics.fact_trip exists; use explicit guarded recreate after checking data';
    END IF;
END
$$;

CREATE TABLE IF NOT EXISTS analytics.dim_location (
    location_id INTEGER PRIMARY KEY,
    borough TEXT NOT NULL,
    zone TEXT NOT NULL,
    service_zone TEXT
);

CREATE TABLE IF NOT EXISTS analytics.dim_calendar (
    date_id DATE PRIMARY KEY,
    day_of_week SMALLINT NOT NULL CHECK (day_of_week BETWEEN 0 AND 6),
    day_name TEXT NOT NULL,
    month SMALLINT NOT NULL CHECK (month BETWEEN 1 AND 12),
    year SMALLINT NOT NULL,
    is_weekend BOOLEAN NOT NULL,
    is_holiday BOOLEAN NOT NULL,
    holiday_name TEXT
);

CREATE TABLE IF NOT EXISTS analytics.dim_weather (
    weather_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    weather_timestamp_utc TIMESTAMPTZ NOT NULL UNIQUE,
    weather_timestamp_nyc TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    weather_date_nyc DATE NOT NULL,
    weather_hour_nyc SMALLINT NOT NULL CHECK (weather_hour_nyc BETWEEN 0 AND 23),
    temperature_2m DOUBLE PRECISION,
    precipitation DOUBLE PRECISION,
    snowfall DOUBLE PRECISION,
    wind_speed_10m DOUBLE PRECISION,
    weather_code BIGINT
);

CREATE TABLE IF NOT EXISTS analytics.fact_trip (
    trip_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_year SMALLINT NOT NULL,
    source_month SMALLINT NOT NULL CHECK (source_month BETWEEN 1 AND 12),
    vendor_id INTEGER,
    pickup_datetime_local TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    dropoff_datetime_local TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    pickup_date DATE NOT NULL,
    pickup_hour SMALLINT NOT NULL CHECK (pickup_hour BETWEEN 0 AND 23),
    pickup_location_id INTEGER NOT NULL REFERENCES analytics.dim_location (location_id),
    dropoff_location_id INTEGER NOT NULL REFERENCES analytics.dim_location (location_id),
    calendar_date_id DATE REFERENCES analytics.dim_calendar (date_id),
    weather_id BIGINT REFERENCES analytics.dim_weather (weather_id),
    passenger_count BIGINT,
    trip_distance DOUBLE PRECISION,
    ratecode_id BIGINT,
    store_and_fwd_flag TEXT,
    payment_type BIGINT,
    fare_amount DOUBLE PRECISION NOT NULL,
    extra DOUBLE PRECISION,
    mta_tax DOUBLE PRECISION,
    tip_amount DOUBLE PRECISION,
    tolls_amount DOUBLE PRECISION,
    improvement_surcharge DOUBLE PRECISION,
    total_amount DOUBLE PRECISION,
    congestion_surcharge DOUBLE PRECISION,
    airport_fee DOUBLE PRECISION,
    cbd_congestion_fee DOUBLE PRECISION,
    pickup_zone_matched BOOLEAN NOT NULL,
    dropoff_zone_matched BOOLEAN NOT NULL,
    calendar_matched BOOLEAN NOT NULL,
    weather_matched BOOLEAN NOT NULL,
    weather_unmatched_reason TEXT,
    _source_file TEXT,
    _ingestion_batch_id TEXT,
    _silver_batch_id TEXT NOT NULL,
    _gold_batch_id TEXT NOT NULL,
    CONSTRAINT chk_fact_calendar_match CHECK (calendar_matched = (calendar_date_id IS NOT NULL)),
    CONSTRAINT chk_fact_weather_match CHECK (weather_matched = (weather_id IS NOT NULL))
);

-- Keep only the partition lookup index during COPY. Other query indexes are
-- intentionally deferred to postload/create_indexes.sql after bulk loading.
CREATE INDEX IF NOT EXISTS fact_trip_source_month_idx
    ON analytics.fact_trip (source_year, source_month);

CREATE TABLE IF NOT EXISTS analytics.etl_load_log (
    dataset TEXT NOT NULL,
    source_year SMALLINT NOT NULL,
    source_month SMALLINT NOT NULL CHECK (source_month BETWEEN 1 AND 12),
    gold_batch_id TEXT NOT NULL,
    source_row_count BIGINT NOT NULL CHECK (source_row_count >= 0),
    loaded_row_count BIGINT CHECK (loaded_row_count >= 0),
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at TIMESTAMPTZ,
    status TEXT NOT NULL,
    PRIMARY KEY (dataset, source_year, source_month)
);

